CREATE OR REPLACE FUNCTION CREDIBANCO_HOL.PLATAFORMA.CONSUMO_POR_SERVICIO(dias_atras NUMBER)
  RETURNS TABLE (SERVICE_TYPE VARCHAR, TOTAL_CREDITS FLOAT) AS $$
    SELECT SERVICE_TYPE, SUM(CREDITS_USED)::FLOAT AS TOTAL_CREDITS
    FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
    WHERE START_TIME >= DATEADD(day, -dias_atras, CURRENT_TIMESTAMP())
    GROUP BY 1 ORDER BY 2 DESC
  $$;

