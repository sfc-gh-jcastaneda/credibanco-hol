CREATE OR REPLACE PROCEDURE CREDIBANCO_HOL.MIGRACION.RECONCILIAR_DIA(p_fecha DATE)
RETURNS VARCHAR LANGUAGE SQL AS
$$
DECLARE v_count NUMBER; v_sum NUMBER;
BEGIN
    v_count := (SELECT COUNT(*) FROM CREDIBANCO_HOL.PAGOS.AUTORIZACIONES WHERE fecha_hora::DATE = :p_fecha);
    v_sum := (SELECT COALESCE(SUM(monto),0) FROM CREDIBANCO_HOL.PAGOS.AUTORIZACIONES WHERE fecha_hora::DATE = :p_fecha);
    INSERT INTO CREDIBANCO_HOL.MIGRACION.RECONCILIACION_DIARIA VALUES (:p_fecha, 'OK', 'Conteo=' || :v_count || ', suma=' || :v_sum, CURRENT_TIMESTAMP());
